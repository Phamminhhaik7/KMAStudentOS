/** Resolve the credit count for a course, by code first then by name. */
export function resolveCredits(code: string, name: string): number {
  if (code && COURSE_CREDITS_BY_CODE[code] !== undefined) {
    return COURSE_CREDITS_BY_CODE[code];
  }
  if (DEFAULT_CREDITS[name] !== undefined) {
    return DEFAULT_CREDITS[name];
  }
  return 3;
}
